-- 17–20: Kiểm thử nghiệp vụ/quyền/đồng thời; hoàn thiện migration, tài liệu và triển
-- khai

-- Schema ở mục 8 là trạng thái đích sau khi hoàn thiện quan hệ và xác thực. Không bỏ qua
-- các phase trước để copy toàn bộ JPA/Security ngay. Các tên migration và lịch chuyển
-- schema cụ thể sẽ được quyết định lúc triển khai, theo dữ liệu đã có khi đó.

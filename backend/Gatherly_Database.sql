-- ============================================================================
-- 2. Quan hệ
-- ============================================================================

-- User có nhiều Event do mình tạo.
-- User có nhiều Registration; Event có nhiều Registration.

-- Mỗi Event bắt buộc có một người tạo. Mỗi Registration bắt buộc thuộc một User và một
-- Event. User và Event có quan hệ nhiều–nhiều thông qua Registration. Dùng entity trung
-- gian vì một đăng ký còn có trạng thái và thời điểm, không chỉ chứa hai khóa ngoại.

-- PK = khóa chính; FK = khóa ngoại; NOT NULL = bắt buộc; UNIQUE = không được trùng. Tên
-- Java dùng camelCase, tên SQL dùng snake_case.


-- ============================================================================
-- 3. User → bảng users
-- ============================================================================

CREATE TABLE users (

    -- Long — Khóa chính, tự sinh.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- String fullName — Họ tên hiển thị.
    full_name VARCHAR(100) NOT NULL,

    -- String email — Duy nhất, trim + lowercase trước khi lưu.
    email VARCHAR(254) NOT NULL,

    -- String passwordHash — Lưu hash; không trả qua API.
    password_hash VARCHAR(255) NOT NULL,

    -- Instant createdAt — Thời điểm tạo.
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Instant updatedAt — Ứng dụng cập nhật khi thay đổi.
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_users_email UNIQUE (email),

    CONSTRAINT ck_users_full_name CHECK (length(btrim(full_name)) > 0),

    CONSTRAINT ck_users_email CHECK (
        length(email) > 0 AND email = lower(btrim(email))
    ),

    CONSTRAINT ck_users_password_hash CHECK (length(btrim(password_hash)) > 0)
);

-- Không lưu confirmPassword; đó là dữ liệu kiểm tra của RegisterRequest. Không trả
-- passwordHash ra API, kể cả API của chính tài khoản. Kiểm tra định dạng email ở DTO; DB
-- bảo vệ tính duy nhất và dạng chuẩn hóa. Trong MVP, quy ước email không phân biệt
-- hoa/thường.

-- Không cần role ORGANIZER: quyền tổ chức được xác định bằng events.organizer_id bằng ID
-- người dùng đã xác thực. Tạo sự kiện không biến người dùng thành một loại tài khoản
-- khác. Nếu sau này có quản trị toàn hệ thống, mới thiết kế thêm quyền quản trị.


-- ============================================================================
-- 4. Event → bảng events
-- ============================================================================

CREATE TABLE events (

    -- Long — Khóa chính, tự sinh.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- User organizer — Người tạo; liên kết users.id.
    organizer_id BIGINT NOT NULL,

    -- String title — Tên sự kiện.
    title VARCHAR(200) NOT NULL,

    -- String description — Nội dung mô tả.
    description TEXT NOT NULL,

    -- String location — Địa điểm đầy đủ.
    location VARCHAR(500) NOT NULL,

    -- Instant startAt — Thời điểm bắt đầu.
    start_at TIMESTAMPTZ NOT NULL,

    -- Instant endAt — Thời điểm kết thúc, sau start_at.
    end_at TIMESTAMPTZ NOT NULL,

    -- Integer capacity — Sức chứa; số nguyên dương.
    capacity INTEGER NOT NULL,

    -- Instant createdAt — Thời điểm tạo.
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Instant updatedAt — Ứng dụng cập nhật khi thay đổi.
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Instant deletedAt — NULL khi chưa xóa; dùng xóa mềm.
    deleted_at TIMESTAMPTZ,

    CONSTRAINT fk_events_organizer FOREIGN KEY (organizer_id)
        REFERENCES users(id) ON DELETE RESTRICT,

    CONSTRAINT ck_events_title CHECK (length(btrim(title)) > 0),

    CONSTRAINT ck_events_description CHECK (length(btrim(description)) > 0),

    CONSTRAINT ck_events_location CHECK (length(btrim(location)) > 0),

    CONSTRAINT ck_events_time CHECK (end_at > start_at),

    CONSTRAINT ck_events_capacity CHECK (capacity > 0)
);

-- Không lưu các dữ liệu suy ra được:

-- - registeredCount = số Registration có status REGISTERED của sự kiện.
-- - remainingSlots = capacity − registeredCount.
-- - UPCOMING khi hiện tại < startAt; ONGOING khi startAt ≤ hiện tại < endAt; ENDED khi
-- hiện tại ≥ endAt.
-- - FULL là trạng thái sức chứa, độc lập với trạng thái thời gian.

-- Không lưu status thời gian để tránh cần job cập nhật và tránh dữ liệu lỗi thời. Trạng
-- thái chỉ tính cho sự kiện chưa xóa.

-- Xóa mềm là lựa chọn triển khai được đề xuất để giữ các đăng ký đã hủy và khóa ngoại.
-- Trên sản phẩm, sự kiện đã xóa biến mất khỏi Khám phá/Tôi tổ chức và truy cập chi tiết
-- thông thường trả không tìm thấy. Lịch sử Đã hủy có thể giữ một mục chỉ đọc với nhãn
-- “Sự kiện đã bị xóa”, không cho đăng ký lại. Không đưa tên/email người tham gia ra API
-- công khai. Tất cả truy vấn thông thường phải lọc deleted_at IS NULL; khóa ngoại không
-- tự lọc giúp ứng dụng.


-- ============================================================================
-- 5. Registration → bảng registrations
-- ============================================================================

CREATE TABLE registrations (

    -- Long — Khóa chính, tự sinh.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Event event — Sự kiện được đăng ký.
    event_id BIGINT NOT NULL,

    -- User user — Người đăng ký.
    user_id BIGINT NOT NULL,

    -- RegistrationStatus — REGISTERED hoặc CANCELLED.
    status VARCHAR(20) NOT NULL DEFAULT 'REGISTERED',

    -- Instant registeredAt — Thời điểm đăng ký gần nhất.
    registered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Instant cancelledAt — NULL nếu đang REGISTERED.
    cancelled_at TIMESTAMPTZ,

    -- Instant createdAt — Lúc tạo bản ghi lần đầu.
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Instant updatedAt — Lúc thay đổi gần nhất.
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_registrations_event FOREIGN KEY (event_id)
        REFERENCES events(id) ON DELETE RESTRICT,

    CONSTRAINT fk_registrations_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE RESTRICT,

    CONSTRAINT uq_registrations_event_user UNIQUE (event_id, user_id),

    CONSTRAINT ck_registrations_status CHECK (
        status IN ('REGISTERED', 'CANCELLED')
    ),

    CONSTRAINT ck_registrations_cancelled_at CHECK (
        (status = 'REGISTERED' AND cancelled_at IS NULL)
        OR (status = 'CANCELLED' AND cancelled_at IS NOT NULL
            AND cancelled_at >= registered_at)
    )
);

-- Ràng buộc quan trọng: UNIQUE(event_id, user_id). Một cặp người–sự kiện chỉ có một dòng
-- trong suốt vòng đời.

-- Đăng ký lần đầu: INSERT status = REGISTERED, registered_at = thời điểm đăng ký,
-- cancelled_at = NULL

-- Hủy đăng ký: UPDATE status = CANCELLED, cancelled_at = thời điểm hủy

-- Đăng ký lại: UPDATE dòng cũ thành REGISTERED, registered_at = thời điểm mới,
-- cancelled_at = NULL

-- Gửi lại khi đã REGISTERED: Không tạo thêm dòng; trả trạng thái đã đăng ký

-- Ví dụ: User 10 đăng ký Event 20, hủy rồi đăng ký lại vẫn dùng cùng registration.id.
-- Bảng chỉ lưu trạng thái/lần gần nhất, không phải nhật ký đầy đủ mọi lần đăng ký và
-- hủy. Không cần bảng lịch sử cho MVP.


-- ============================================================================
-- 6. Phân chia trách nhiệm bảo vệ dữ liệu
-- ============================================================================

-- ID duy nhất; email duy nhất; cặp event/user duy nhất: PK, UNIQUE trong DB

-- Người tạo, sự kiện và người tham gia phải tồn tại: FK trong DB

-- capacity > 0, end_at > start_at, status hợp lệ: CHECK trong DB, kèm validation phù hợp
-- ở ứng dụng

-- Trường bắt buộc, độ dài, email đúng định dạng: DTO validation; DB bảo vệ NOT NULL/độ
-- dài/không rỗng

-- Tạo/sửa chỉ khi start_at vẫn ở tương lai: Service, dùng thời điểm hiện tại khi xử lý

-- Chủ sở hữu không tự đăng ký sự kiện của mình: Service

-- Chỉ chủ sở hữu được sửa/xóa/xem danh sách người tham gia: Spring Security + kiểm tra
-- organizer_id trong Service

-- Không sửa/hủy/đăng ký khi sự kiện đã bắt đầu: Service, kiểm tra lại sau khi lấy khóa

-- Không vượt capacity; không giảm capacity dưới số đăng ký đang hiệu lực: Transaction +
-- khóa dòng Event + đếm lại

-- Chỉ xóa sự kiện chưa bắt đầu và không có đăng ký hiệu lực: Cùng transaction + khóa
-- dòng Event + đếm lại

-- CHECK đơn giản không kiểm tra được tổng số hàng trong bảng registrations. UNIQUE chỉ
-- chống đăng ký trùng; không tự chống vượt sức chứa.


-- ============================================================================
-- 7. Xử lý đồng thời cho phase 16
-- ============================================================================

-- Khi nhiều request tranh chỗ cuối, dùng chính dòng events làm điểm khóa chung. Event đã
-- tồn tại nên không gặp bài toán khóa một dòng Registration chưa được tạo.

-- Luồng đăng ký trong một transaction ở mức READ COMMITTED:

-- 1. SELECT Event theo id, deleted_at IS NULL, FOR UPDATE.
-- 2. Sau khi lấy được khóa, đọc thời điểm hiện tại mới và kiểm tra sự kiện chưa bắt đầu.
-- Không dùng thời điểm đã chụp trước lúc chờ khóa.
-- 3. Kiểm tra người dùng không phải người tổ chức.
-- 4. Kiểm tra Registration hiện tại; nếu đang REGISTERED thì trả trạng thái đã đăng ký.
-- 5. Đếm các Registration REGISTERED bằng một câu truy vấn tiếp theo sau khi đã có khóa
-- Event. Nếu đã đủ capacity thì từ chối.
-- 6. INSERT dòng mới hoặc kích hoạt lại dòng CANCELLED; COMMIT để nhả khóa. Lỗi thì
-- ROLLBACK.

-- Hủy đăng ký, sửa capacity/thời gian và xóa mềm cũng phải khóa cùng dòng Event trước,
-- rồi mới kiểm tra và cập nhật Registration/Event. Giữ thứ tự khóa Event → Registration
-- nhất quán. Mọi đường ghi liên quan đều phải tuân theo quy ước này; việc ghi SQL trực
-- tiếp bỏ qua quy ước vẫn có thể phá vỡ giới hạn sức chứa.

-- Ví dụ capacity = 30, hiện có 29 người: A khóa Event, kiểm tra 29 và đăng ký thành 30.
-- B chờ. Sau khi A commit, B lấy khóa rồi truy vấn đếm mới thấy 30, nên không được đăng
-- ký.


-- ============================================================================
-- 8. SQL schema đích
-- ============================================================================

-- Đây là SQL tham chiếu cho toàn bộ MVP, không phải yêu cầu tạo tất cả bảng ngay ở phase
-- hiện tại. Script chưa được chạy với PostgreSQL trong phiên thiết kế này. Không dùng
-- script để ghi đè database đã có dữ liệu; khi triển khai dùng migration theo từng
-- phase.

-- Khám phá: lọc sự kiện chưa xóa, sắp xếp thời gian tăng dần.
CREATE INDEX idx_events_start ON events (start_at, id)
    WHERE deleted_at IS NULL;

-- Danh sách “Tôi tổ chức”.
CREATE INDEX idx_events_organizer ON events (organizer_id, start_at, id)
    WHERE deleted_at IS NULL;

-- COUNT và danh sách người tham gia còn hiệu lực.
CREATE INDEX idx_registrations_active_event
    ON registrations (event_id, registered_at DESC, id DESC)
    WHERE status = 'REGISTERED';

-- Danh sách đăng ký của người dùng theo trạng thái đăng ký.
CREATE INDEX idx_registrations_user_status
    ON registrations (user_id, status, registered_at DESC, id DESC);

-- Index UNIQUE(event_id, user_id) đã hỗ trợ truy vấn theo event_id ở vị trí đầu; không
-- cần thêm index đơn event_id. Tab Sắp tới/Đã kết thúc vẫn cần JOIN events để lọc thời
-- gian; index user/status không thay thế việc đó. Tìm kiếm ILIKE '%từ khóa%' trên
-- title/location chưa được index B-tree trên thời gian tối ưu; phase đầu có thể chấp
-- nhận với dữ liệu nhỏ, sau đó đo truy vấn trước khi thêm trigram/full-text.

-- updated_at DEFAULT chỉ chạy lúc INSERT, không tự đổi khi UPDATE. Service hoặc JPA
-- auditing phải cập nhật trường này. registered_at/cancelled_at phải được gán theo thời
-- điểm thao tác thực tế sau khi lấy khóa, tránh dùng mặc định CURRENT_TIMESTAMP nếu
-- transaction đã phải chờ lâu. TIMESTAMPTZ lưu thời điểm, không lưu tên múi giờ gốc;
-- Java dùng Instant, giao diện đổi sang Asia/Ho_Chi_Minh khi hiển thị/nhập giờ Việt Nam.


-- ============================================================================
-- 9. Ánh xạ sang JPA
-- ============================================================================

-- User: @Entity, @Table(name = "users"), id Long

-- Event.organizer: @ManyToOne(fetch = FetchType.LAZY), @JoinColumn(name =
-- "organizer_id", nullable = false)

-- Registration.user: @ManyToOne(fetch = FetchType.LAZY), @JoinColumn(name = "user_id",
-- nullable = false)

-- Registration.event: @ManyToOne(fetch = FetchType.LAZY), @JoinColumn(name = "event_id",
-- nullable = false)

-- Registration.status: enum RegistrationStatus với REGISTERED/CANCELLED;
-- @Enumerated(EnumType.STRING)

-- Các cột TIMESTAMPTZ: Instant

-- MVP có thể dùng quan hệ một chiều; chưa cần List<Event>/List<Registration> trong User
-- hay List<Registration> trong Event. Truy vấn danh sách qua Repository giúp phân trang
-- và tránh vô tình tải toàn bộ collection. Không dùng CascadeType.REMOVE từ User/Event
-- tới các bản ghi liên quan. Không trả Entity trực tiếp làm response; dùng
-- DTO/projection và fetch join phù hợp để tránh N+1. Session/JWT thuộc lựa chọn xác thực
-- ở phase 14; chưa tự thêm refresh_tokens khi chưa chốt cách đăng nhập.


